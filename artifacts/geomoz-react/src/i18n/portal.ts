export type PortalCopyKey = keyof typeof PORTAL_CATALOGS.pt;
export type PortalCatalogLocale = keyof typeof PORTAL_CATALOGS;
export const PORTAL_TRANSLATED_LANGUAGES = ["pt", "en", "es", "fr"] as const;
export function resolvedPortalLocale(language: string): PortalCatalogLocale {
  const base = language.toLowerCase().replace(/_/g, "-").split("-")[0];
  return Object.prototype.hasOwnProperty.call(PORTAL_CATALOGS, base)
    ? base as PortalCatalogLocale : "en";
}
export function portalText(language: string, key: PortalCopyKey): string {
  const catalog = PORTAL_CATALOGS[resolvedPortalLocale(language)];
  return catalog[key] || PORTAL_CATALOGS.en[key];
}

